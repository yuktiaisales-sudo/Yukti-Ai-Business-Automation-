class Lead {
  final String name;
  final String mobile;
  final String email;
  final String project;
  final String source;
  final String status;
  final DateTime createdDate;

  Lead({
    required this.name,
    required this.mobile,
    required this.email,
    required this.project,
    required this.source,
    required this.status,
    required this.createdDate,
  });
}